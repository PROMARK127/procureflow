import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { mutate } from '../lib/workflow.ts';

test('購買ワークフローをPostgreSQLで実行する',async t => {
  const db = new PGlite();
  t.after(() => db.close());
  const sql = async name => readFile(new URL('../sql/'+name+'.sql',import.meta.url),'utf8');
  await db.exec(await sql('001_schema'));
  await db.exec(await sql('seed'));
  await db.exec(await sql('seed'));
  assert.equal((await db.query('SELECT count(*)::int AS n FROM transactions')).rows[0].n,6);
  const ids = Object.fromEntries((await db.query('SELECT role,id FROM users')).rows.map(u=>[u.role,u.id]));
  const catalog = Object.fromEntries((await db.query('SELECT name,id FROM catalog_items')).rows.map(i=>[i.name,i.id]));
  const suppliers = (await db.query('SELECT id FROM suppliers ORDER BY id')).rows;
  const act = (role,action,rest={}) => db.transaction(tx => mutate(tx,{actor:ids[role],action,...rest}));
  const rejected = async (role,action,rest,pattern) => assert.rejects(act(role,action,rest),pattern);
  const request = item => act('buyer','request',{item,quantity:2,reason:'検証用の備品'});
  const state = async id => (await db.query('SELECT * FROM transactions WHERE id=$1',[id])).rows[0];

  const {id} = await request(catalog['ノートPC']);
  assert.equal((await state(id)).total,296000);
  await rejected('manager','approve',{id},/承認順序/);
  await rejected('buyer','order',{id},/承認済み/);
  await act('approver','approve',{id});
  assert.equal((await state(id)).status,'pending');
  await act('manager','return',{id,comment:'確認'});
  await act('buyer','resubmit',{id,item:catalog['モニター'],quantity:2,reason:'修正済み'});
  await act('approver','approve',{id});
  assert.equal((await state(id)).status,'approved');
  assert.equal((await db.query('SELECT count(*)::int AS n FROM approval_steps WHERE request_id=$1',[id])).rows[0].n,3);
  await rejected('buyer','order',{id},/採用見積/);
  await act('manager','quote',{id,supplier:suppliers[0].id,amount:55000});
  await act('manager','quote',{id,supplier:suppliers[1].id,amount:57000});
  const quotes = (await db.query('SELECT id FROM quotations WHERE request_id=$1 ORDER BY amount',[id])).rows;
  await act('manager','select',{id,quote:quotes[1].id,reason:'比較'});
  await rejected('buyer','order',{id},/承認額/);
  await act('manager','select',{id,quote:quotes[0].id,reason:'比較'});
  await act('buyer','order',{id});
  await rejected('buyer','order',{id},/未発注/);
  await act('supplier','confirm',{id});
  await rejected('buyer','receive',{id,quantity:3},/超えています/);
  await act('accounting','invoice',{id,amount:55000,date:'2026-11-18'});
  await rejected('accounting','pay',{id},/検収が完了/);
  await act('buyer','receive',{id,quantity:2});
  await db.query('UPDATE invoices SET amount=1 WHERE id=$1',[(await state(id)).invoice_id]);
  await rejected('accounting','pay',{id},/金額が一致/);
  await db.query('UPDATE invoices SET amount=55000 WHERE id=$1',[(await state(id)).invoice_id]);
  await act('accounting','pay',{id});
  await rejected('accounting','pay',{id},/未払い/);
  const paid = await state(id);
  assert.equal(paid.payment_status,'paid');
  assert.equal(paid.received_quantity,2);
  assert.equal(paid.invoice_amount,paid.order_amount);
  assert.ok(paid.order_id);
  const denied = await request(catalog['マウス']);
  await act('approver','reject',{...denied,comment:'不要'});
  assert.equal((await state(denied.id)).status,'rejected');
  await rejected('buyer','order',denied,/承認済み/);
});